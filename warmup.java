public class warmup {
    public static void main(String[] args) {
        int total = 0;
        for (int i = 1; i <= 5; i++) {
            total += i;
        }
        System.out.println(total / 2);
    }

    public static void arrayTest() {
        int [] a = {3,7,2,9};
        for (int i = 0; i <= a.length; i++) {
            System.out.println(a[i]);
        }
    }
}

